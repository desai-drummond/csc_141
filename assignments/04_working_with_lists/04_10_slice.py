# Create a list of numbers from 1 to 10
numbers = list(range(1, 11))

# Print the first three numbers using slicing
print(numbers[:3])

# Print the middle three numbers using slicing
print(numbers[3:6])

# Print the last three numbers using slicing
print(numbers[-3:])

