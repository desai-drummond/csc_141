# Create a variable for the alien's color. The if block runs.
alien_color = 'green'

# Check whether the alien's color is green.
if alien_color == 'green':
    # This message prints because the alien is green.
    print("The player just earned 5 points for shooting the alien.")
else:
    print("The player just earned 10 points for shooting the alien.")


